let balanceKopecks = 0;

export const demoOperations = entries
    .map(([timestamp, type, amount, description]) => {
        const credit = type === 'TopUp' || type === 'TransferIn' || type === 'Refund';
        const balanceBefore = balanceKopecks / 100;
        balanceKopecks += (credit ? 1 : -1) * Math.round(amount * 100);
        const suffix = timestamp.replace(/\D/g, '');

        return {
            id: `00000000-0000-4000-8000-${suffix}`,
            referenceId: `10000000-0000-4000-8000-${suffix}`,
            type,
            amount,
            currency: 'RUB',
            balanceBefore,
            balanceAfter: balanceKopecks / 100,
            description,
            createdAt: `${timestamp}:00Z`,
        };
    })
    .reverse();
